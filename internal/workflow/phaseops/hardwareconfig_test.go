// TestStageHardwareConfig_FailureWarns pins the last resort: when both add
// attempts fail (a locked index here) nothing is staged and the WARN names the
// manual command. Not parallel: it swaps the global logger.
//
//nolint:paralleltest // swaps the global logger to capture the WARN
func TestStageHardwareConfig_FailureWarns(t *testing.T) {
	repo := initTestRepo(t)
	path := filepath.Join(repo, "hardware-configuration.nix")
	require.NoError(t, os.WriteFile(path, []byte("modulesPath config, }\n"), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(repo, ".git", "index.lock"), nil, 0o600))

	logged := &bytes.Buffer{}
	previous := log.Logger
	log.Logger = log.Output(logged)

	t.Cleanup(func() { log.Logger = previous })

	stageHardwareConfig(path)

	assert.Contains(t, logged.String(), "could not stage the hardware config, run git -C")

	_, err := execGitIn(t, repo, "ls-files", "--error-unmatch", "hardware-configuration.nix")
	assert.Error(t, err, "nothing may be staged when both add attempts fail")
}

