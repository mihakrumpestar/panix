// TestIsWriteModeGenerator pins the generator shape panix can never capture:
// the flag may sit in the command or the args, and a wrapper still invokes the
// built-in generator.
func TestIsWriteModeGenerator(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		generator attributes.Generator
		want      bool
	}{
		{
			name:      "write-mode nixos-generate-config",
			generator: attributes.Generator{Command: []string{"nixos-generate-config"}, Args: []string{"--no-filesystems"}},
			want:      true,
		},
		{
			name:      "printing nixos-generate-config",
			generator: attributes.Generator{Command: []string{"nixos-generate-config"}, Args: []string{"--show-hardware-config"}},
		},
		{
			name:      "flag in the command",
			generator: attributes.Generator{Command: []string{"nixos-generate-config", "--show-hardware-config"}, Args: []string{}},
		},
		{
			name:      "wrapped write-mode generator",
			generator: attributes.Generator{Command: []string{"env", "FOO=1", "/run/current-system/sw/bin/nixos-generate-config"}, Args: []string{}},
			want:      true,
		},
		{
			name:      "another generator",
			generator: attributes.Generator{Command: []string{"nixos-facter"}, Args: []string{}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, tt.want, IsWriteModeGenerator(tt.generator))
		})
	}
}

// TestGenerateHardwareConfig_RefusesWriteMode pins the choke point every caller
// shares: a write-mode generator is refused before it can rewrite /etc/nixos.
func TestGenerateHardwareConfig_RefusesWriteMode(t *testing.T) {
	t.Parallel()

	mach := newLocalTransferMachine(t, true)
	mach.HardwareConfig.Path = "/tmp/hardware-configuration.nix"
	mach.HardwareConfig.Generate = attributes.Generator{Command: []string{"nixos-generate-config"}, Args: []string{}}
	exc, phaseLog := testutil.NewDryRunExecutioner(t, mach, phase.Inspect)

	err := GenerateHardwareConfig(exc, mach)

	require.ErrorIs(t, err, ErrWriteModeGenerator)
	assert.Empty(t, testutil.CommandLines(t, phaseLog), "the refused generator must not run")
}

// TestWriteHardwareConfig pins that only a recognized nixos-generate-config
// result is written; any other captured stream fails without leaving a file.
func TestWriteHardwareConfig(t *testing.T) {
	t.Parallel()

	for _, tt := range hardwareConfigWriteCases {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			runHardwareConfigWriteCase(t, tt)
		})
	}
}

func runHardwareConfigWriteCase(t *testing.T, tt hardwareConfigWriteCase) {
	t.Helper()

	path := filepath.Join(t.TempDir(), "nested", "hardware-configuration.nix")

	err := writeHardwareConfig(path, tt.output)
	if tt.wantErr != "" {
		require.Error(t, err)
		assert.Contains(t, err.Error(), tt.wantErr)
		assert.NoFileExists(t, path)

		return
	}

	require.NoError(t, err)

	content, err := os.ReadFile(path) //nolint:gosec // test-controlled temp path
	require.NoError(t, err)
	assert.Equal(t, tt.wantContent, string(content))
}

// initTestRepo creates a git repository in a fresh temp dir.
func initTestRepo(t *testing.T) string {
	t.Helper()

	repo := t.TempDir()
	gitInTestRepo(t, repo, "init", "-q")

	return repo
}

// gitInTestRepo runs git in dir with identity and signing pinned, since this
// environment's default git config demands signing; output is returned.
func gitInTestRepo(t *testing.T, dir string, args ...string) string {
	t.Helper()

	out, err := execGitIn(t, dir, args...)
	require.NoError(t, err, out)

	return out
}

// execGitIn runs git in dir like gitInTestRepo but returns the error so callers
// can assert failures.
func execGitIn(t *testing.T, dir string, args ...string) (string, error) {
	t.Helper()

	gitArgs := append([]string{"-C", dir, "-c", "commit.gpgsign=false", "-c", "user.email=t@t", "-c", "user.name=t"}, args...)

	//nolint:gosec // test-controlled arguments
	out, err := exec.CommandContext(context.Background(), "git", gitArgs...).CombinedOutput()

	return string(out), err
}

// TestStageHardwareConfig pins the staging matrix: an untracked file becomes
// git-visible, a gitignored file is force-staged, and a tracked file's index
// entry stays untouched.
func TestStageHardwareConfig(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		gitignored bool
		tracked    bool
	}{
		{name: "untracked file is staged"},
		{name: "gitignored file is force-staged", gitignored: true},
		{name: "tracked and modified file stays a no-op", tracked: true},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			runStageHardwareConfigCase(t, tt.gitignored, tt.tracked)
		})
	}
}

func runStageHardwareConfigCase(t *testing.T, gitignored, tracked bool) {
	t.Helper()

	repo := initTestRepo(t)

	if gitignored {
		require.NoError(t, os.WriteFile(filepath.Join(repo, ".gitignore"), []byte("hardware-configuration.nix\n"), 0o600))
	}

	path := filepath.Join(repo, "hardware-configuration.nix")
	require.NoError(t, os.WriteFile(path, []byte("original\n"), 0o600))

	if tracked {
		gitInTestRepo(t, repo, "add", "hardware-configuration.nix")
		require.NoError(t, os.WriteFile(path, []byte("modified\n"), 0o600))

		indexBefore := gitInTestRepo(t, repo, "ls-files", "-s", "hardware-configuration.nix")

		stageHardwareConfig(path)

		// A tracked path is already in the index: neither -N nor -fN may change it.
		assert.Equal(t, indexBefore, gitInTestRepo(t, repo, "ls-files", "-s", "hardware-configuration.nix"))

		return
	}

	stageHardwareConfig(path)

	// --error-unmatch exits non-zero unless the path is in the index; for the
	// gitignored case this proves the force retry ran.
	gitInTestRepo(t, repo, "ls-files", "--error-unmatch", "hardware-configuration.nix")
}

