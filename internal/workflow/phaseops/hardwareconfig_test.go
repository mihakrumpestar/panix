// validHardwareConfigOutput mirrors nixos-generate-config
// --show-hardware-config output, including its single trailing newline.
const validHardwareConfigOutput = `# Do not modify this file!  It was generated by ‘nixos-generate-config’
# and may be overwritten by future invocations.  Please make changes
# to /etc/nixos/configuration.nix instead.
{ config, lib, pkgs, modulesPath, ... }:

{
  imports = [ ];

  boot.initrd.availableKernelModules = [ ];
  boot.initrd.kernelModules = [ ];
  boot.kernelModules = [ "kvm-intel" ];
  boot.extraModulePackages = [ ];

  nixpkgs.hostPlatform = lib.mkDefault "x86_64-linux";
}
`

// truncatedHardwareConfigOutput is a valid config cut off before the
// closing brace (the PTY can drop the last line of a captured stream).
const truncatedHardwareConfigOutput = `# Do not modify this file!  It was generated by ‘nixos-generate-config’
# and may be overwritten by future invocations.  Please make changes
# to /etc/nixos/configuration.nix instead.
{ config, lib, pkgs, modulesPath, ... }:

{
  imports = [ ];
`

type hardwareConfigWriteCase struct {
	name        string
	output      string
	wantErr     string
	wantContent string
}

var hardwareConfigWriteCases = []hardwareConfigWriteCase{
	{
		name:        "valid config is written",
		output:      validHardwareConfigOutput,
		wantContent: validHardwareConfigOutput,
	},
	{
		name:    "empty output",
		output:  "",
		wantErr: "produced no output",
	},
	{
		name:    "stderr warning before the config",
		output:  "warning: Git tree '/repo' is dirty\n" + validHardwareConfigOutput,
		wantErr: "unexpected hardware config output",
	},
	{
		name:    "truncated config",
		output:  truncatedHardwareConfigOutput,
		wantErr: "truncated hardware config output",
	},
}

// stubNixosGenerateConfig writes a fake nixos-generate-config into a fresh temp
// dir and returns the dir to prepend to PATH, so no NixOS machine is needed.
func stubNixosGenerateConfig(t *testing.T, output string) string {
	t.Helper()

	dir := t.TempDir()
	outputPath := filepath.Join(dir, "output.txt")
	require.NoError(t, os.WriteFile(outputPath, []byte(output), 0o600))

	script := "#!/bin/sh\ncat " + outputPath + "\n"
	stubPath := filepath.Join(dir, "nixos-generate-config")
	//nolint:gosec // the stub must be executable to be found on PATH
	require.NoError(t, os.WriteFile(stubPath, []byte(script), 0o700))

	return dir
}

